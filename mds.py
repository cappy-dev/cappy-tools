# ---------- Markdown parser (standard library only) ----------

class MarkdownParser:
    """Converts Markdown to HTML without any external libraries."""

    def __init__(self):
        self.list_depth = 0
        self.list_types = []

    def parse(self, text):
        lines = text.split("\n")
        html_parts = []
        i = 0
        while i < len(lines):
            line = lines[i]

            # Close lists when indentation decreases
            if self.list_depth > 0 and not line.startswith(" " * (self.list_depth * 4)) and not line.strip().startswith(("- ", "* ", "+ ", "1.")):
                while self.list_depth > 0:
                    tag = self.list_types.pop()
                    html_parts.append(f"</{tag}>")
                    self.list_depth -= 1

            # Headings
            heading_match = re.match(r"^(#{1,6})\s+(.*)", line)
            if heading_match:
                level = len(heading_match.group(1))
                content = self._inline(heading_match.group(2))
                html_parts.append(f"<h{level}>{content}</h{level}>")
                i += 1
                continue

            # Horizontal rule
            if re.match(r"^(---+|\*\*\*+|___+)\s*$", line):
                html_parts.append("<hr>")
                i += 1
                continue

            # Fenced code block
            if line.startswith("```"):
                lang = line[3:].strip()
                code_lines = []
                i += 1
                while i < len(lines) and not lines[i].startswith("```"):
                    code_lines.append(escape(lines[i]))
                    i += 1
                i += 1  # skip closing ```
                code_body = "\n".join(code_lines)
                lang_attr = f' class="language-{escape(lang)}"' if lang else ""
                html_parts.append(f"<pre><code{lang_attr}>{code_body}</code></pre>")
                continue

            # Blockquote
            if line.startswith("> "):
                quote_lines = []
                while i < len(lines) and lines[i].startswith("> "):
                    quote_lines.append(lines[i][2:])
                    i += 1
                quote_content = self.parse("\n".join(quote_lines))
                html_parts.append(f"<blockquote>{quote_content}</blockquote>")
                continue

            # Unordered list
            ul_match = re.match(r"^(\s*)([-*+])\s+(.*)", line)
            if ul_match and not ul_match.group(1):
                if self.list_depth == 0 or self.list_types[-1] != "ul":
                    html_parts.append("<ul>")
                    self.list_depth += 1
                    self.list_types.append("ul")
                content = self._inline(ul_match.group(3))
                html_parts.append(f"<li>{content}</li>")
                i += 1
                continue

            # Ordered list
            ol_match = re.match(r"^(\s*)(\d+)\.\s+(.*)", line)
            if ol_match and not ol_match.group(1):
                if self.list_depth == 0 or self.list_types[-1] != "ol":
                    html_parts.append("<ol>")
                    self.list_depth += 1
                    self.list_types.append("ol")
                content = self._inline(ol_match.group(3))
                html_parts.append(f"<li>{content}</li>")
                i += 1
                continue

            # Empty line: paragraph break
            if not line.strip():
                i += 1
                continue

            # Paragraph (collect consecutive non-empty, non-special lines)
            para_lines = []
            while i < len(lines):
                l = lines[i]
                if not l.strip():
                    break
                if re.match(r"^#{1,6}\s", l):
                    break
                if l.startswith("```") or l.startswith("> "):
                    break
                if re.match(r"^[-*+]\s", l):
                    break
                if re.match(r"^\d+\.\s", l):
                    break
                if re.match(r"^(---+|\*\*\*+|___+)\s*$", l):
                    break
                para_lines.append(l)
                i += 1
            if para_lines:
                content = self._inline(" ".join(para_lines))
                html_parts.append(f"<p>{content}</p>")
            continue

        # Close any remaining lists
        while self.list_depth > 0:
            tag = self.list_types.pop()
            html_parts.append(f"</{tag}>")
            self.list_depth -= 1

        return "\n".join(html_parts)

    def _inline(self, text):
        """Process inline formatting: bold, italic, code, links, images."""
        # Inline code (must come before other processing)
        text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
        # Images
        text = re.sub(r"!\[([^\]]*)\]\(([^)]+)\)", r'<img src="\2" alt="\1">', text)
        # Links
        text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', text)
        # Bold (double asterisk or double underscore)
        text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
        text = re.sub(r"__(.+?)__", r"<strong>\1</strong>", text)
        # Italic (single asterisk or single underscore)
        text = re.sub(r"\*(.+?)\*", r"<em>\1</em>", text)
        text = re.sub(r"_(.+?)_", r"<em>\1</em>", text)
        # Escape remaining HTML
        return text


# ---------- Front matter parser ----------

def parse_front_matter(text):
    """Extract YAML-like front matter from markdown text.

    Returns (metadata_dict, body_text).
    Supports simple key: value pairs. Strings, numbers, booleans.
    Multi-line strings not supported (keep it simple).
    """
    if not text.startswith("---"):
        return {}, text

    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}, text

    meta_str = parts[1].strip()
    body = parts[2].strip()

    meta = {}
    for line in meta_str.split("\n"):
        line = line.strip()
        if not line or ":" not in line:
            continue
        key, _, value = line.partition(":")
        key = key.strip()
        value = value.strip()
        # Strip surrounding quotes
        if (value.startswith('"') and value.endswith('"')) or \
           (value.startswith("'") and value.endswith("'")):
            value = value[1:-1]
        # Boolean
        if value.lower() in ("true", "yes"):
            value = True
        elif value.lower() in ("false", "no"):
            value = False
        # Number
        else:
            try:
                value = int(value)
            except ValueError:
                try:
                    value = float(value)
                except ValueError:
                    pass
        meta[key] = value

    return meta, body


# ---------- Site builder ----------

def find_markdown_files(content_dir):
    """Recursively find .md files in content_dir."""
    files = []
    for root, _, filenames in os.walk(content_dir):
        for fn in sorted(filenames):
            if fn.endswith(".md"):
                files.append(os.path.join(root, fn))
    return files


def slugify(text):
    """Turn a title into a URL-friendly slug."""
    text = text.lower().strip()
    text = re.sub(r"[^\w\s-]", "", text)
    text = re.sub(r"[\s_]+", "-", text)
    text = re.sub(r"-+", "-", text)
    return text.strip("-")


def build_post_entry(href, title, date_str):
    """Build an HTML list item for the index page."""
    date_attr = f' datetime="{date_str}"' if date_str else ""
    date_display = date_str[:10] if date_str else ""
    return f'<li>{date_display:12s}<a href="{href}">{escape(title)}</a></li>'


def render_template(template, **kwargs):
    """Simple {{key}} template substitution."""
    result = template
    for key, value in kwargs.items():
        result = result.replace("{{" + key + "}}", str(value))
    return result


def build_site(content_dir, output_dir, template_str=None, index_template_str=None, base_url=""):
    """Build the static site from markdown content.

    Args:
        content_dir: Path to directory containing .md files.
        output_dir: Path to write HTML output.
        template_str: HTML template for posts. Uses default if None.
        index_template_str: HTML template for index page. Uses default if None.
        base_url: Optional base URL for the site (used in meta tags).
    """
    content_path = Path(content_dir)
    output_path = Path(output_dir)

    if not content_path.exists():
        print(f"Error: content directory '{content_dir}' not found.", file=sys.stderr)
        sys.exit(1)

    # Clean and create output directory
    if output_path.exists():
        shutil.rmtree(output_path)
    output_path.mkdir(parents=True, exist_ok=True)

    # Copy any static assets
    static_dir = content_path / "static"
    if static_dir.exists():
        shutil.copytree(static_dir, output_path / "static")

    # Load custom template if provided
    if template_str is None:
        template_str = DEFAULT_TEMPLATE
    elif os.path.isfile(template_str):
        template_str = Path(template_str).read_text()

    if index_template_str is None:
        index_template_str = DEFAULT_INDEX_TEMPLATE
    elif os.path.isfile(index_template_str):
        index_template_str = Path(index_template_str).read_text()

    # Collect all markdown files
    md_files = find_markdown_files(content_path)
    if not md_files:
        print("No markdown files found in content directory.", file=sys.stderr)
        sys.exit(1)

    parser = MarkdownParser()
    posts = []

    for md_file in md_files:
        # Skip files inside static/
        if "static" in Path(md_file).parts:
            continue

        raw = Path(md_file).read_text(encoding="utf-8")
        meta, body = parse_front_matter(raw)

        title = meta.get("title", Path(md_file).stem.replace("-", " ").title())
        date = meta.get("date", "")
        lang = meta.get("lang", "en")
        slug = meta.get("slug", slugify(title))

        # Determine output path
        rel_path = Path(md_file).relative_to(content_path)
        if rel_path == Path("index.md"):
            out_name = "index.html"
        else:
            out_name = f"{slug}.html"

        # Convert markdown to HTML
        html_content = parser.parse(body)

        # Render page
        page_html = render_template(
            template_str,
            title=escape(title),
            content=html_content,
            lang=lang,
            base_url=base_url,
        )

        out_file = output_path / out_name
        out_file.write_text(page_html, encoding="utf-8")
        print(f"  {rel_path} -> {out_name}")

        # Track for index (skip index.md itself)
        if rel_path != Path("index.md"):
            posts.append({
                "title": title,
                "date": str(date),
                "href": out_name,
            })

    # Build index page if there are posts and no index.md
    index_exists = any(Path(f).relative_to(content_path) == Path("index.md") for f in md_files)

    if posts and not index_exists:
        posts.sort(key=lambda p: p.get("date", ""), reverse=True)
        post_list_html = "\n".join(
            build_post_entry(p["href"], p["title"], p["date"])
            for p in posts
        )
        index_html = render_template(
            index_template_str,
            title="Home",
            post_list=post_list_html,
            lang="en",
        )
        (output_path / "index.html").write_text(index_html, encoding="utf-8")
        print("  (auto) -> index.html")

    print(f"\nBuilt {len(posts)} post(s) + index in {output_path}")


def serve_site(directory, port=8000):
    """Start a simple HTTP server for the built site."""
    from http.server import HTTPServer, SimpleHTTPRequestHandler

    os.chdir(directory)
    server = HTTPServer(("", port), SimpleHTTPRequestHandler)
    print(f"Serving {directory} at http://localhost:{port}")
    print("Press Ctrl+C to stop.")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nServer stopped.")


def init_site(directory):
    """Create a starter site with example markdown files."""
    site_dir = Path(directory)
    content_dir = site_dir / "content"
    content_dir.mkdir(parents=True, exist_ok=True)

    # Example index (optional)
    (content_dir / "index.md").write_text(
        "---\ntitle: My Site\ndate: 2026-01-01\n---\n\n"
        "# Welcome\n\nThis is my static site built with markdown-to-static.\n\n"
        "Check out the [about page](about.html).\n",
        encoding="utf-8",
    )

    # Example post
    (content_dir / "hello.md").write_text(
        "---\ntitle: Hello World\ndate: 2026-06-27\n---\n\n"
        "# Hello World\n\n"
        "This is my first post. It was generated from a Markdown file.\n\n"
        "## Features\n\n"
        "- Zero dependencies\n"
        "- Front matter support\n"
        "- Code highlighting classes\n"
        "- Automatic index page\n\n"
        "Here is some code:\n\n"
        "```python\nprint('Hello from markdown-to-static!')\n```\n\n"
        "**Bold text** and *italic text* work too.\n",
        encoding="utf-8",
    )

    # Example about page
    (content_dir / "about.md").write_text(
        "---\ntitle: About\ndate: 2026-06-27\n---\n\n"
        "# About\n\n"
        "This site is built with markdown-to-static, a minimal Python static site generator.\n\n"
        "> Simple tools for simple sites.\n\n"
        "No frameworks. No build steps. Just Python and Markdown.\n",
        encoding="utf-8",
    )

    print(f"Starter site created in {site_dir}")
    print(f"  {content_dir}/index.md")
    print(f"  {content_dir}/hello.md")
    print(f"  {content_dir}/about.md")
    print(f"\nBuild it with:")
    print(f"  python3 mds.py build {site_dir}/content {site_dir}/output")


def main():
    parser = argparse.ArgumentParser(
        prog="mds",
        description="markdown-to-static: Minimal Python static site generator.",
    )
    parser.add_argument("--version", action="version", version=f"%(prog)s {VERSION}")
    sub = parser.add_subparsers(dest="command")

    # build
    b = sub.add_parser("build", help="Build static site from markdown files")
    b.add_argument("content_dir", help="Directory containing .md files")
    b.add_argument("output_dir", help="Directory to write HTML output")
    b.add_argument("--template", help="Path to custom HTML template file", default=None)
    b.add_argument("--index-template", help="Path to custom index template file", default=None)
    b.add_argument("--base-url", help="Base URL for the site", default="")

    # serve
    s = sub.add_parser("serve", help="Serve built site locally")
    s.add_argument("directory", help="Directory with HTML files to serve")
    s.add_argument("--port", type=int, default=8000, help="Port number (default: 8000)")

    # init
    i = sub.add_parser("init", help="Create a starter site with example files")
    i.add_argument("directory", nargs="?", default="my-site", help="Directory name (default: my-site)")

    args = parser.parse_args()

    if args.command == "build":
        build_site(
            args.content_dir,
            args.output_dir,
            template_str=args.template,
            index_template_str=args.index_template,
            base_url=args.base_url,
        )
    elif args.command == "serve":
        serve_site(args.directory, port=args.port)
    elif args.command == "init":
        init_site(args.directory)
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
